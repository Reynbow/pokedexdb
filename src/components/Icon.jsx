const rectsFor = (rows) => {
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === "#") run += 1;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={run} height={1} />);
      x += run;
    }
  });
  return rects;
};

const CACHE = new Map();

export default function Icon({ name, className = "", title, ...rest }) {
  const rows = ICONS[name];
  if (!rows) return null;
  if (!CACHE.has(name)) CACHE.set(name, rectsFor(rows));
  return (
    <svg
      className={`icon ${className}`.trim()}
      viewBox="0 0 12 12"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {CACHE.get(name)}
    </svg>
  );
}

/** The Game Boy menu cursor ▶, drawn on an 8×10 grid. */
export function Cursor({ className = "" }) {
  return (
    <svg className={`cursor ${className}`.trim()} viewBox="0 0 8 10" aria-hidden="true" focusable="false">
      <rect x="0" y="0" width="2" height="10" />
      <rect x="2" y="1" width="2" height="8" />
      <rect x="4" y="2" width="2" height="6" />
      <rect x="6" y="3" width="2" height="4" />
    </svg>
  );
}
